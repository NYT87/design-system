// Builds dist/ from icons.config.json: an SVG sprite, an ESM module with an inline helper, types, and JSON.
// Source icons come from lucide-static (ISC); a missing name fails the build instead of shipping a gap.
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRANDS } from './brands.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const lucideDir = dirname(require.resolve('lucide-static/package.json'));
const config = JSON.parse(readFileSync(join(root, 'icons.config.json'), 'utf8'));
const nodes = JSON.parse(readFileSync(join(lucideDir, 'icon-nodes.json'), 'utf8'));

const attr = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const toMarkup = (list) => list.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${attr(v)}"`).join(' ')}/>`).join('');

const icons = {};
const missing = [];
for (const name of config.lucide) {
  if (!nodes[name]) { missing.push(name); continue; }
  if (icons[name]) throw new Error(`Duplicate icon "${name}" in icons.config.json`);
  icons[name] = { viewBox: '0 0 24 24', body: toMarkup(nodes[name]) };
}
if (missing.length) throw new Error(`Not in lucide-static ${JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8')).version}: ${missing.join(', ')}`);
for (const [name, b] of Object.entries(BRANDS)) {
  if (icons[name]) throw new Error(`Brand "${name}" clashes with a Lucide icon`);
  icons[name] = { viewBox: b.viewBox, body: `<path fill="currentColor" stroke="none" d="${b.d}"/>` };
}
const names = Object.keys(icons).sort();
const sorted = Object.fromEntries(names.map((n) => [n, icons[n]]));

const symbols = names.map((n) => `<symbol id="${n}" viewBox="${sorted[n].viewBox}">${sorted[n].body}</symbol>`).join('\n');
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols}\n</svg>\n`;

const js = `// GENERATED by scripts/build.mjs from icons.config.json. Do not edit.
// Icons: Lucide (ISC, https://lucide.dev), plus the brand marks in scripts/brands.mjs.
export const icons = ${JSON.stringify(sorted, null, 1)};

export const names = Object.keys(icons);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

/**
 * The icon as an inline <svg> string, self-contained (it does not need the stylesheet or the sprite).
 * Decorative by default (aria-hidden). Pass \`label\` when the icon alone carries meaning.
 */
export function icon(name, { label, size, class: className } = {}) {
  const i = icons[name];
  if (!i) throw new Error(\`Unknown icon "\${name}". See https://nyt87.github.io/design-system/#/icons\`);
  const a11y = label ? \`role="img" aria-label="\${esc(label)}"\` : 'aria-hidden="true"';
  const cls = className ? \`ds-icon \${esc(className)}\` : 'ds-icon';
  const dim = size ? \` width="\${esc(size)}" height="\${esc(size)}"\` : ' width="1.25em" height="1.25em"';
  return \`<svg class="\${cls}" viewBox="\${i.viewBox}"\${dim} fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" \${a11y}>\${i.body}</svg>\`;
}

/** The whole sprite as an inline, hidden <svg>: put it once at the top of <body> so <use href="#name"> resolves without a request. */
export const sprite = '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" width="0" height="0" style="position:absolute">\\n'
  + names.map((n) => \`<symbol id="\${n}" viewBox="\${icons[n].viewBox}">\${icons[n].body}</symbol>\`).join('\\n')
  + '\\n</svg>';
`;

const dts = `// GENERATED by scripts/build.mjs. Do not edit.
export type IconName =
  | ${names.map((n) => `'${n}'`).join('\n  | ')};

export interface IconDef { viewBox: string; body: string }
export interface IconOptions { label?: string; size?: string; class?: string }

export const icons: Record<IconName, IconDef>;
export const names: IconName[];
export function icon(name: IconName, options?: IconOptions): string;
export const sprite: string;
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/sprite.svg'), sprite);
writeFileSync(join(root, 'dist/icons.js'), js);
writeFileSync(join(root, 'dist/icons.d.ts'), dts);
writeFileSync(join(root, 'dist/icons.json'), JSON.stringify(sorted, null, 1) + '\n');
copyFileSync(join(lucideDir, 'LICENSE'), join(root, 'LICENSE-LUCIDE'));
console.log(`built ${names.length} icons (${config.lucide.length} Lucide + ${Object.keys(BRANDS).length} brand marks): dist/sprite.svg, icons.js, icons.d.ts, icons.json`);
